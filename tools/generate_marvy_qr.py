#!/usr/bin/env python3
"""Generate a module-aligned QR and its supplied color mark for LVGL.

Requires Pillow. The original public follow-code attachment is checksum-pinned.
Only the visible supplied QR is sampled: no URL is opened and no payload is
regenerated. Both RGB565 images are read-only Flash assets. Native RGB565
avoids LVGL's whole-image ARGB8888 conversion for indexed images.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

from PIL import Image


SOURCE_SHA256 = "89685d406c85ce42d8e043a76f81c582fb8fe5f47e35f901bae4dba6cf838fd2"
MODULE_COUNT = 37
SOURCE_MODULE = 20
SOURCE_ORIGIN = 60
MODULE_SIZE = 4
QUIET_MODULES = 4
QR_SIZE = (MODULE_COUNT + QUIET_MODULES * 2) * MODULE_SIZE
MARK_SIZE = 44
MARK_OFFSET = 68
MARK_SOURCE_BOX = (320, 320, 540, 540)


def image_source(root: Path) -> Image.Image:
    source = root / "assets/images/marvy-follow-qr.jpg"
    if hashlib.sha256(source.read_bytes()).hexdigest() != SOURCE_SHA256:
        raise ValueError("Follow QR differs from the supplied attachment; review before regenerating")
    with Image.open(source) as image:
        if image.size != (860, 860):
            raise ValueError("Follow QR source must retain its original 860x860 geometry")
        return image.convert("RGB")


def make_images(image: Image.Image) -> tuple[Image.Image, Image.Image]:
    """Preserve each visible module on a 4px grid, plus the original color mark."""
    if image.size != (860, 860):
        raise ValueError("Expected the original QR attachment geometry")
    image = image.convert("RGB")
    base = Image.new("1", (QR_SIZE, QR_SIZE), 1)
    for row in range(MODULE_COUNT):
        for col in range(MODULE_COUNT):
            x = SOURCE_ORIGIN + col * SOURCE_MODULE + SOURCE_MODULE // 2
            y = SOURCE_ORIGIN + row * SOURCE_MODULE + SOURCE_MODULE // 2
            if max(image.getpixel((x, y))) >= 128:
                continue
            left = (QUIET_MODULES + col) * MODULE_SIZE
            top = (QUIET_MODULES + row) * MODULE_SIZE
            base.paste(0, (left, top, left + MODULE_SIZE, top + MODULE_SIZE))
    mark = image.crop(MARK_SOURCE_BOX).resize((MARK_SIZE, MARK_SIZE), Image.Resampling.LANCZOS)
    return base, mark


def encode_rgb565(image: Image.Image) -> bytes:
    pixels = bytearray()
    rgb = image.convert("RGB").tobytes()
    for offset in range(0, len(rgb), 3):
        red, green, blue = rgb[offset:offset + 3]
        value = ((red >> 3) << 11) | ((green >> 2) << 5) | (blue >> 3)
        pixels.extend((value & 255, value >> 8))
    return bytes(pixels)


def preview_image(root: Path) -> Image.Image:
    """Reconstruct the two descriptors with the actual RGB565 quantization."""
    base, mark = make_images(image_source(root))
    rgb565 = encode_rgb565(mark)
    quantized = Image.new("RGB", mark.size)
    colors = []
    for offset in range(0, len(rgb565), 2):
        value = rgb565[offset] | rgb565[offset + 1] << 8
        colors.append((((value >> 11) & 31) * 255 // 31,
                       ((value >> 5) & 63) * 255 // 63,
                       (value & 31) * 255 // 31))
    quantized.putdata(colors)
    preview = base.convert("RGB")
    preview.paste(quantized, (MARK_OFFSET, MARK_OFFSET))
    return preview


def descriptor(symbol: str, size: int, stride: int, color_format: str, pixels: bytes) -> str:
    rows = [f"static const LV_ATTRIBUTE_MEM_ALIGN uint8_t {symbol}_pixels[] = {{"]
    for offset in range(0, len(pixels), 16):
        rows.append("    " + ", ".join(f"0x{v:02x}" for v in pixels[offset:offset + 16]) + ",")
    rows.append("};\n")
    rows.append(f'''const lv_image_dsc_t {symbol} = {{
    .header = {{
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = {color_format},
        .flags = 0,
        .w = {size},
        .h = {size},
        .stride = {stride},
    }},
    .data_size = sizeof({symbol}_pixels),
    .data = {symbol}_pixels,
}};
''')
    return "\n".join(rows)


def build_assets(root: Path) -> tuple[str, str]:
    base, mark = make_images(image_source(root))
    header = f'''#pragma once

#include "lvgl.h"

#define MARVY_QR_SIZE {QR_SIZE}
#define MARVY_QR_MARK_OFFSET {MARK_OFFSET}
#define MARVY_QR_MARK_SIZE {MARK_SIZE}

/* Position the mark at QR origin + MARK_OFFSET, with neither image scaled. */
LV_IMAGE_DECLARE(marvy_follow_qr);
LV_IMAGE_DECLARE(marvy_follow_qr_mark);
'''
    source = ("/* Generated by tools/generate_marvy_qr.py; do not edit pixel arrays.\n"
              f" * Supplied QR JPEG SHA-256: {SOURCE_SHA256}\n"
              " * 37 modules at 4px/module, 4-module white quiet zone on every side.\n"
              " * Both images: native little-endian RGB565, read directly from Flash. */\n\n"
              '#include "marvy_qr.h"\n\n' +
              descriptor("marvy_follow_qr", QR_SIZE, QR_SIZE * 2,
                         "LV_COLOR_FORMAT_RGB565", encode_rgb565(base)) + "\n" +
              descriptor("marvy_follow_qr_mark", MARK_SIZE, MARK_SIZE * 2,
                         "LV_COLOR_FORMAT_RGB565", encode_rgb565(mark)))
    return header, source


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify generated source without writing")
    parser.add_argument("--preview", type=Path, help="Write a reconstructed RGB565-accurate PNG preview")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    header, source = build_assets(root)
    for path, text in ((root / "main/marvy_qr.h", header), (root / "main/marvy_qr.c", source)):
        if args.check:
            if not path.is_file() or path.read_text() != text:
                raise SystemExit(f"Generated QR asset is stale: {path.relative_to(root)}")
        else:
            path.write_text(text)
    if args.preview:
        args.preview.parent.mkdir(parents=True, exist_ok=True)
        preview_image(root).save(args.preview)
    print("Follow QR: 180x180 RGB565, 64800 Flash bytes; mark: 44x44 RGB565, 3872 Flash bytes")


if __name__ == "__main__":
    main()
