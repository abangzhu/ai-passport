#!/usr/bin/env python3
"""Generate small, transparent LVGL RGB565A8 assets from the supplied logo.

Requires Pillow. The original PNG remains unchanged; generated descriptors
reference Flash-resident bytes directly, without a PNG decoder or full-image
heap allocation. RGB565A8 is a little-endian RGB565 plane followed by A8.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

from PIL import Image, ImageOps


SOURCE_SHA256 = "4ab5057babe4ee8a9f07c99fd5cd7b105e2751d5d7dd36c035ce935ba56efa99"
ASSETS = (("welcome", 112), ("badge", 20))


def resize_logo(image: Image.Image, size: int) -> Image.Image:
    """Fit the full image in a transparent square without cropping or distortion."""
    if size <= 0:
        raise ValueError("Logo size must be positive")
    resized = ImageOps.contain(image.convert("RGBA"), (size, size), Image.Resampling.LANCZOS)
    canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    canvas.alpha_composite(resized, ((size - resized.width) // 2, (size - resized.height) // 2))
    return canvas


def encode_rgb565a8(image: Image.Image) -> bytes:
    """Encode LVGL's separate color/alpha planes, not interleaved RGB565+A8."""
    colors = bytearray()
    alpha = bytearray()
    rgba = image.convert("RGBA").tobytes()
    for offset in range(0, len(rgba), 4):
        red, green, blue, opacity = rgba[offset:offset + 4]
        rgb565 = ((red >> 3) << 11) | ((green >> 2) << 5) | (blue >> 3)
        colors.extend((rgb565 & 0xFF, rgb565 >> 8))
        alpha.append(opacity)
    return bytes(colors + alpha)


def image_source(root: Path) -> Image.Image:
    source = root / "assets/images/marvy-logo.png"
    if hashlib.sha256(source.read_bytes()).hexdigest() != SOURCE_SHA256:
        raise ValueError("Logo source differs from the supplied attachment; review it before regenerating")
    with Image.open(source) as image:
        return image.convert("RGBA")


def build_assets(root: Path) -> tuple[str, str]:
    image = image_source(root)
    header = '''#pragma once

#include "lvgl.h"

#define MARVY_LOGO_WELCOME_WIDTH 112
#define MARVY_LOGO_WELCOME_HEIGHT 112
#define MARVY_LOGO_BADGE_SIZE 20

LV_IMAGE_DECLARE(marvy_logo_welcome);
LV_IMAGE_DECLARE(marvy_logo_badge);
'''
    parts = [
        '/* Generated by tools/generate_marvy_logo.py; do not edit pixel arrays.\n'
        f' * Original user-supplied PNG SHA-256: {SOURCE_SHA256}\n'
        ' * RGB565A8: little-endian color plane, then an unmodified A8 plane. */\n',
        '#include "marvy_logo.h"\n',
    ]
    for name, size in ASSETS:
        pixels = encode_rgb565a8(resize_logo(image, size))
        symbol = f"marvy_logo_{name}"
        parts.append(f"static const LV_ATTRIBUTE_MEM_ALIGN uint8_t {symbol}_pixels[] = {{")
        for offset in range(0, len(pixels), 16):
            parts.append("    " + ", ".join(f"0x{value:02x}" for value in pixels[offset:offset + 16]) + ",")
        parts.append("};\n")
        parts.append(f'''const lv_image_dsc_t {symbol} = {{
    .header = {{
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_RGB565A8,
        .flags = 0,
        .w = {size},
        .h = {size},
        .stride = {size * 2},
    }},
    .data_size = sizeof({symbol}_pixels),
    .data = {symbol}_pixels,
}};
''')
    return header, "\n".join(parts).rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify checked-in assets without writing")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    header, source = build_assets(root)
    for path, text in ((root / "main/marvy_logo.h", header), (root / "main/marvy_logo.c", source)):
        if args.check:
            if not path.is_file() or path.read_text() != text:
                raise SystemExit(f"Generated logo asset is stale: {path.relative_to(root)}")
        else:
            path.write_text(text)
    original = image_source(root)
    for name, size in ASSETS:
        path = root / f"assets/images/marvy-logo-{name}.png"
        resized = resize_logo(original, size)
        if args.check:
            if not path.is_file():
                raise SystemExit(f"Missing logo preview: {path.relative_to(root)}")
            with Image.open(path) as existing:
                if existing.size != resized.size or existing.convert("RGBA").tobytes() != resized.tobytes():
                    raise SystemExit(f"Generated logo preview is stale: {path.relative_to(root)}")
        else:
            resized.save(path)
        print(f"{name}: {size}x{size}, RGB565A8, {size * size * 3} Flash pixel bytes")


if __name__ == "__main__":
    main()
